#!/usr/bin/env python3
"""Generate src/title_gfx.asm: the ACADIA logo for the title screen (T-REL-1).

The logo is an ANTIC mode D bitmap (160 x LOGO_H pixels, 4 colours,
40 bytes a line): bold block letters in grass green, edged in beach
yellow like the islands, with a black drop shadow on the sea.  Each
letter is a 5 x 7 pattern scaled 4 x 6 (mode D pixels are square, so
the letters stand tall), with the corners
where a stroke steps diagonally cut at 45 degrees.  Pixel values: 0 background (sea), 1 COLPF0 (green
fill), 2 COLPF1 (yellow edge), 3 COLPF2 (shadow).

Usage: python3 tools/mktitle.py > src/title_gfx.asm
"""

import sys

W, LOGO_H = 160, 46
SX, SY = 4, 6           # each pattern cell is SX x SY pixels
GAP = 4                 # pixels between letters
SHADOW = (2, 2)         # drop shadow offset (x, y)
TOP = 1                 # first line of the letters

GLYPHS = {
    "A": [".###.",
          "#...#",
          "#...#",
          "#####",
          "#...#",
          "#...#",
          "#...#"],
    "C": [".####",
          "#....",
          "#....",
          "#....",
          "#....",
          "#....",
          ".####"],
    "D": ["####.",
          "#...#",
          "#...#",
          "#...#",
          "#...#",
          "#...#",
          "####."],
    "I": [".###.",
          "..#..",
          "..#..",
          "..#..",
          "..#..",
          "..#..",
          ".###."],
}
WORD = "ACADIA"


def glyph_pixels(g):
    """Scaled glyph as a set of (x, y), with the outside corners cut."""
    rows, cols = len(g), len(g[0])

    def on(r, c):
        return 0 <= r < rows and 0 <= c < cols and g[r][c] == "#"

    px = set()
    for r in range(rows):
        for c in range(cols):
            if on(r, c):
                for y in range(SY):
                    for x in range(SX):
                        px.add((c * SX + x, r * SY + y))
    # a filled cell whose outer corner is open on three sides, where the
    # stroke steps on diagonally (the cell beside it, one row in, is
    # filled: the shoulders of A, C and D), loses that corner's triangle
    for r in range(rows):
        for c in range(cols):
            if not on(r, c):
                continue
            for dr, dc in ((-1, -1), (-1, 1), (1, -1), (1, 1)):
                if on(r + dr, c) or on(r, c + dc) or on(r + dr, c + dc):
                    continue
                if not on(r - dr, c + dc):
                    continue    # only where the stroke steps diagonally
                for y in range(SY):
                    for x in range(SX):
                        # distance into the corner, 0 at the corner pixel
                        cx = x if dc < 0 else SX - 1 - x
                        cy = y if dr < 0 else SY - 1 - y
                        if cx * (SY - 1) + cy * (SX - 1) < (SX - 1) * (SY - 1):
                            px.discard((c * SX + x, r * SY + y))
    return px, cols * SX


def logo():
    letters = [glyph_pixels(GLYPHS[ch]) for ch in WORD]
    width = sum(w for _, w in letters) + GAP * (len(letters) - 1)
    x0 = (W - width - SHADOW[0]) // 2
    fill = set()
    for px, w in letters:
        fill |= {(x0 + x, TOP + y) for x, y in px}
        x0 += w + GAP
    edge = set()
    for x, y in fill:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                p = (x + dx, y + dy)
                if p not in fill:
                    edge.add(p)
    body = fill | edge
    shadow = {(x + SHADOW[0], y + SHADOW[1]) for x, y in body} - body
    img = [[0] * W for _ in range(LOGO_H)]
    for pset, v in ((shadow, 3), (edge, 2), (fill, 1)):
        for x, y in pset:
            assert 0 <= x < W and 0 <= y < LOGO_H, (x, y)
            img[y][x] = v
    return img


def main():
    img = logo()
    out = sys.stdout
    out.write("; =====================================================================\n")
    out.write(";  TITLE_GFX.ASM -- the ACADIA logo, ANTIC mode D (generated by\n")
    out.write(";  tools/mktitle.py; do not edit).  %d lines of 40 bytes.\n" % LOGO_H)
    out.write("; =====================================================================\n\n")
    out.write("LOGO_H  =  %d           ; mode D lines\n\n" % LOGO_H)
    out.write("        *= TITLEGFX\n")
    out.write("LOGO\n")
    for y, row in enumerate(img):
        data = []
        for b in range(W // 4):
            v = 0
            for i in range(4):
                v = (v << 2) | row[b * 4 + i]
            data.append(v)
        for half in (data[:20], data[20:]):
            out.write("        .BYTE " + ",".join("$%02X" % v for v in half) + "\n")
    # preview as a comment, 1 char per pixel
    out.write("\n; preview: . sea, # green, + yellow, : shadow\n")
    for row in img:
        out.write(";  " + "".join(".#+:"[v] for v in row) + "\n")


main()
