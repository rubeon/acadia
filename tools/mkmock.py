# Map: . sea, G grass, 1-9 items.  Both islands show every item once.
MAP = [
    "....................",
    "....................",
    "..GGGGG.......GGGG..",
    ".GG1GG2G.....GG7GGG.",
    ".G3GGGG4G...G1GG2GG.",
    "GGG5GG6GG8..GG6GG3G9",
    ".GG7GGGG9...GGG4G5G8",
    "..GGGGGG.....GGGGGG.",
    "...GGGG.......GGG...",
    "....................",
    "....................",
]

PIX = {".": 0, "G": 1, "D": 2, "Y": 3}

# Tile numbering: 0 sea, 1-16 grass with beach mask 0-15, 17-25 items 1-9
T_SEA, T_GRASS, T_ITEM = 0, 1, 17
N, E, S, W = 1, 2, 4, 8


def grass_tile(mask):
    art = [["G"] * 8 for _ in range(8)]
    for i in range(8):
        if mask & N: art[0][i] = "Y"
        if mask & S: art[7][i] = "Y"
        if mask & W: art[i][0] = "Y"
        if mask & E: art[i][7] = "Y"
    return ["".join(r) for r in art]


def tile_bytes(art):
    """Return (left char 8 bytes, right char 8 bytes) for 8x8 art."""
    assert len(art) == 8 and all(len(r) == 8 for r in art), art
    left, right = [], []
    for row in art:
        p = [PIX[c] for c in row]
        left.append(p[0] << 6 | p[1] << 4 | p[2] << 2 | p[3])
        right.append(p[4] << 6 | p[5] << 4 | p[6] << 2 | p[7])
    return left, right


tiles = [("sea", False, ["........"] * 8)]
for m in range(16):
    tiles.append(("grass, beach mask %d" % m, False, grass_tile(m)))
for k in range(1, 10):
    tiles.append(ITEMS[k])


def is_land(r, c):
    if r < 0 or r >= ROWS or c < 0 or c >= COLS:
        return False
    return MAP[r][c] in "G1234567"


def square_tile(r, c):
    ch = MAP[r][c]
    if ch == ".":
        return T_SEA
    if ch == "G":
        mask = 0
        if not is_land(r - 1, c): mask |= N
        if not is_land(r + 1, c): mask |= S
        if not is_land(r, c - 1): mask |= W
        if not is_land(r, c + 1): mask |= E
        return T_GRASS + mask
    return T_ITEM + int(ch) - 1


assert len(MAP) == ROWS and all(len(r) == COLS for r in MAP), "map size"
for k in range(1, 10):
    for half in ([r[:10] for r in MAP], [r[10:] for r in MAP]):
        assert sum(r.count(str(k)) for r in half) == 1, "item %d" % k

out = []
out.append("; =====================================================================")
out.append(";  MOCK_DATA.ASM -- generated by tools/mkmock.py; do not edit by hand")
out.append(";  Q3 palette mock-up: mode 5 map font and screen")
out.append("; =====================================================================")
out.append("")
out.append("        *= $3000")
out.append("MAPFONT")
for n, (name, inv, art) in enumerate(tiles):
    l, r = tile_bytes(art)
    out.append("; tile %d: %s%s" % (n, name, " (inverse chars)" if inv else ""))
    out.append("        .BYTE " + ",".join("$%02X" % b for b in l))
    out.append("        .BYTE " + ",".join("$%02X" % b for b in r))
out.append("")
out.append("        *= $3400")
out.append("MAPSCR")
for r in range(ROWS):
    codes = []
    for c in range(COLS):
        t = square_tile(r, c)
        inv = 0x80 if tiles[t][1] else 0
        codes += [(2 * t) | inv, (2 * t + 1) | inv]
    out.append("; row %d  %s" % (r, MAP[r]))
    out.append("        .BYTE " + ",".join("$%02X" % b for b in codes[:20]))
    out.append("        .BYTE " + ",".join("$%02X" % b for b in codes[20:]))

with open("src/mock_data.asm", "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote src/mock_data.asm: %d tiles, %d chars" % (len(tiles), 2 * len(tiles)), file=sys.stderr)
