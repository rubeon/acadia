; =====================================================================
;  MEM_A800.ASM -- memory map of the Atari 800XL build (XEX)
;
;  Every fixed address the game is assembled at, or keeps a screen,
;  font or buffer at, is set here and nowhere else (T-5200-0), so a
;  5200 cartridge build can supply its own map (MEM_5200.ASM) and
;  include the same modules.  ARCHITECTURE.md section 3 explains each
;  block; keep the two in step.
;
;  Include after HW_A800.ASM and before any module.
; =====================================================================

; ---------------------------------------------------------------------
;  Code
; ---------------------------------------------------------------------
CODE1   =  $2000        ; start-up, services, map, stats part 1, display
CODE2   =  $5000        ; game logic (ECONOMY.ASM ... STATUS.ASM)

; ---------------------------------------------------------------------
;  Screens, display lists, P/M graphics (RAM)
; ---------------------------------------------------------------------
MAPSCR  =  $3400        ; map screen memory, 928 bytes (DISPLAY.ASM, D67)
DLBASE  =  $3800        ; display list page: DLIST, HDLIST,
                        ; TDLIST, CTDLIST (one page, one SDLSTL store)
PMAREA  =  $4000        ; P/M graphics, 1K aligned (double-line)
HELPSCR =  $4400        ; 11 x 40 help screen, after P/M memory

; ---------------------------------------------------------------------
;  RAM variables (VARS.ASM), cleared by VARS_INIT
; ---------------------------------------------------------------------
VARBASE =  $3900
VARPAGES = 7            ; $3900-$3FFF

; ---------------------------------------------------------------------
;  Fonts (generated: FONT_MAP.ASM by tools/mkfont.py, FONT_STAT.ASM by
;  tools/mkstat.py), 1K aligned.  MFAmf = map m's font f (D56).
; ---------------------------------------------------------------------
MFAC    =  $3000        ; the corner font: rows 0-2, 19-21 on every map (D65)
MFA00   =  $4800        ; STANDARD font 0
MFA01   =  $8800        ; STANDARD font 1
MFA02   =  $8C00        ; STANDARD font 2
MFA10   =  $A800        ; RANDOM font
PSFONTA =  $A000        ; pause band font PSFONT (D69)
TTFONTA =  $A400        ; title screen font TTFONT (D70)
HLPFNTA =  $4C00        ; help font HLPFONT, then the wave frames WVDATA
STFONTA =  $9800        ; status bar font STFONT (D54)

; ---------------------------------------------------------------------
;  Map data (ISLANDS.ASM, generated by tools/mkfont.py)
; ---------------------------------------------------------------------
ISLDATA =  $9000        ; the live map's tables (RAM, D56)
MAPSRC  =  $AC00        ; each map's data block MAPS0 ...; TRAIL.ASM and
                        ; STATS2.ASM follow, all below $BC00 (D57)

; ---------------------------------------------------------------------
;  Title screen graphics (TITLE_GFX.ASM, generated by tools/mktitle.py)
; ---------------------------------------------------------------------
TITLEGFX = $8000        ; title graphics (D70): logo, scene, colour
                        ; tables, 1828 bytes, up to $8723

; ---------------------------------------------------------------------
;  Stats screen chart bitmap and text (D61): blocks free after a game
; ---------------------------------------------------------------------
CTBM0   =  $9C00        ; chart lines 0-24 (not loaded, D57)
CTBM1   =  $BC00        ; lines 25-49 (not loaded, D57)
CTBM2   =  $3400        ; lines 50-63: MAPSCR (the map, drawn again later)
CTTXT   =  $4400        ; four mode 4 lines: HELPSCR (the help screen's memory)
