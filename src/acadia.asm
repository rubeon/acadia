;    $3400-$35B7  map screen (11 x 40, mode 5)
;    $3800-       display list
;    $3900-$3FFF  RAM variables (VARS.ASM)
;    $4000-$43FF  P/M graphics, double-line (SPRITES.ASM)
;    $4800-$4BFF  map font 1
; =====================================================================

