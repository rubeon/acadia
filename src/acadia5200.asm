; =====================================================================
;  ACADIA5200 -- the Atari 5200 build: a 32K cartridge (D62)
;
;  Top-level file of the cartridge; ACADIA.ASM is the 800's.  Both
;  include the same modules; this one swaps in the 5200's hardware
;  equates, memory map, platform hooks and input layer.  Assemble with
;  ATasm:  atasm -Isrc -obuild/acadia5200.obj src/acadia5200.asm,
;  then tools/mkcart.py makes the cartridge image (make 5200).
;
;  ROM ($4000-$BFFF) in order (MEM_5200.ASM has the addresses):
;    CODE1     start-up, services, map, stats part 1, display
;    MFA00 ... the map, help and status bar fonts, 1K each
;    DLBASE    display lists, then the island constants
;    MAPSRC    each map's block, then code block 2, the wakes and
;              stats part 2
;    TITLEGFX  the title logo
;    CARTHDR   the cartridge header
;  RAM ($0000-$3FFF) holds only reserved blocks (*= *+n): nothing is
;  loaded there.
; =====================================================================

        .INCLUDE "hw_5200.asm"
        .INCLUDE "mem_5200.asm"
        .INCLUDE "tiles.asm"

; ---------------------------------------------------------------------
;  Entry point, from the BIOS through the header's start vector: a
;  fresh stack, then the start-up shared with the 800 (MAIN.ASM)
; ---------------------------------------------------------------------
        *= CODE1
START
        CLD
        LDX #$FF
        TXS
        JMP MAIN_INIT

        .INCLUDE "main.asm"
        .INCLUDE "plat_5200.asm"
        .INCLUDE "input5200.asm"
        .INCLUDE "math.asm"
        .INCLUDE "rand.asm"
        .INCLUDE "tic.asm"
        .INCLUDE "text.asm"
        .INCLUDE "sprites.asm"
        .INCLUDE "cursor.asm"
        .INCLUDE "map.asm"
        .INCLUDE "stats.asm"
        .INCLUDE "display.asm"  ; ends with the fonts and display lists

; ---------------------------------------------------------------------
;  Island constants after the display lists, then (at MAPSRC) each
;  map's block (generated by tools/mkfont.py)
; ---------------------------------------------------------------------
        .INCLUDE "islands.asm"

; ---------------------------------------------------------------------
;  Code block 2: game logic, after the maps' blocks
; ---------------------------------------------------------------------
        .INCLUDE "economy.asm"
        .INCLUDE "boats.asm"
        .INCLUDE "fish.asm"
        .INCLUDE "weather.asm"
        .INCLUDE "pirates.asm"
        .INCLUDE "rebels.asm"
        .INCLUDE "ai.asm"
        .INCLUDE "sound.asm"
        .INCLUDE "music.asm"
        .INCLUDE "pause.asm"
        .INCLUDE "help.asm"
        .INCLUDE "screens.asm"
        .INCLUDE "news.asm"
        .INCLUDE "setup.asm"
        .INCLUDE "title.asm"
        .INCLUDE "demo.asm"
        .INCLUDE "shade.asm"
        .INCLUDE "maps.asm"
        .INCLUDE "status.asm"
        .INCLUDE "trail.asm"
        .INCLUDE "stats2.asm"
ROMEND                          ; must stay below TITLEGFX (MKCART.PY)

; ---------------------------------------------------------------------
;  Title logo (ROM)
; ---------------------------------------------------------------------
        .INCLUDE "title_gfx.asm"

; ---------------------------------------------------------------------
;  RAM: the variables and the live map's tables, reserved only
; ---------------------------------------------------------------------
        .INCLUDE "vars.asm"
        *= ISLDATA
        .INCLUDE "isl_live5200.asm"

; ---------------------------------------------------------------------
;  Cartridge header (5200 BIOS): 20 characters of title (screen codes,
;  bits 6-7 the colour) at $BFE8, the copyright year's last two digits
;  at $BFFC-$BFFD, the start vector at $BFFE.  The BIOS shows its title
;  screen (logo, the title, "COPYRIGHT 19" + the two digits) for a few
;  seconds, then jumps to START.  $BFFD = $FF would skip that screen,
;  but then the BIOS jumps before it sets its vectors (VIMIRQ,
;  VVBLKI, ...) and the first IRQ crashes (D62).
; ---------------------------------------------------------------------
        *= CARTHDR
        .SBYTE "       ACADIA       "
        .SBYTE "26"     ; the year (screen codes, PF0)
        .WORD START
