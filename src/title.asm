; =====================================================================
;  TITLE.ASM -- the title screen (T-REL-1, R-MODE-5)
;
;  Shown at start-up, before the setup screen.  The name is in ANTIC
;  mode 7 (one line of 20 characters); the credits and the prompt are
;  in mode 2 (lines of 40 characters).  The screen has the same
;  shape as the setup screen: a mode 7 band, a blank line, then 18
;  mode 2 lines, and the same colours (D16), so the two screens look
;  like a pair.
;
;  Its own display list (TDLIST) is in page $38, like the setup and
;  help screens, and it uses the map's screen memory, like the setup
;  screen does: the setup screen follows the title screen and clears
;  the same memory, and GAME_START draws the map again.
;
;  START or fire goes on to the setup screen.  The title tune starts
;  here and carries on into the setup screen (D45).
;
;  The original game is credited by name, with a line saying that this
;  is an independent game and not a Mattel product (T-REL-1).
; =====================================================================

GS_TITLE =  5            ; GSTATE while the title screen is up

TI_ROWS  =  18           ; mode 2 lines on the title screen
TI_LEN   =  40           ; characters in a mode 2 line

; The text itself (generated by tools/gen-title.py)
        .INCLUDE "title_text.asm"

; ---------------------------------------------------------------------
;  TITLE_ENTER -- show the title screen.
;  Trashes A, X, Y.
; ---------------------------------------------------------------------
TITLE_ENTER
        JSR MUS_TITLE   ; the title tune starts here (D45)
        LDA #GS_TITLE
        STA GSTATE
        LDA #0
        STA TI_ARM
        STA SPRHP       ; cursors off screen (HPOS 0)
        STA SPRHP+1
        JSR TI_DRAW
        LDA #C_LIGHT    ; the name in mode 7: yellow (as the setup
        STA COLOR0      ; screen's title, C_TITLE)
        LDA #ROMFONT    ; the OS font: the mode 7 name needs it
        STA CHBAS
        LDA #<TDLIST    ; same page as DLIST: one store switches
        STA SDLSTL
        RTS

; ---------------------------------------------------------------------
;  TITLE_FRAME -- each frame of the title screen: once everything has
;  been let go, START or fire goes on to the setup screen.
;  Trashes A, X, Y.
; ---------------------------------------------------------------------
TITLE_FRAME
        LDA FIRE0
        ORA FIRE1
        STA TI_F
        LDA TI_ARM
        BNE TF_ON
        LDA TI_F        ; wait until everything is let go
        ORA CONKEY
        ORA KEYDOWN
        BNE TF_RTS
        INC TI_ARM
        LDA #0
        STA TI_OLDF
        STA TI_OLDC
        LDA #0
        STA TI_F
TF_RTS  RTS
TF_ON   LDA TI_F        ; fire pressed: on to the setup screen
        BEQ TF_STRT
        LDA TI_OLDF
        BNE TF_STRT     ; held last frame too: not a new press
        JMP SETUP_ENTER
TF_STRT LDA CONKEY      ; START pressed: on to the setup screen
        AND #1
        BEQ TF_KEY
        LDA TI_OLDC
        AND #1
        BNE TF_KEY
TF_GO   JMP SETUP_ENTER
TF_KEY  LDA TI_F
        STA TI_OLDF
        LDA CONKEY
        STA TI_OLDC
        RTS

; ---------------------------------------------------------------------
;  TI_DRAW -- clear the screen memory, then copy the title text into
;  it: the name in the mode 7 band, the credits in the mode 2 lines.
;  Trashes A, X, Y, ZPTR, TPTR.
; ---------------------------------------------------------------------
TI_DRAW
        LDA #0          ; clear the three pages the screen uses
        LDX #0
TI_CLR  STA TI_SCR,X
        STA TI_SCR+$100,X
        STA TI_SCR+$200,X
        INX
        BNE TI_CLR
        LDX #TI_N-1
TI_LINE STX TI_I
        LDA TI_LIN,X    ; the mode 2 line
        JSR TI_ROWADR
        LDX TI_I
        LDA TI_LO,X
        STA TPTR
        LDA TI_HI,X
        STA TPTR+1
        LDY #TI_LEN-1
TI_CHR  LDA (TPTR),Y
        STA (ZPTR),Y
        DEY
        BPL TI_CHR
        LDX TI_I
        DEX
        BPL TI_LINE
        LDX #19         ; the name
TI_NAM  LDA TI_NAME,X
        STA TI_SCR,X
        DEX
        BPL TI_NAM
        RTS

; ---------------------------------------------------------------------
;  TI_ROWADR -- ZPTR = TI_TXT + line * 40.
;  In: A = the mode 2 line (0-17).  Trashes A, Y.
; ---------------------------------------------------------------------
TI_ROWADR
        STA TI_T
        ASL A
        ASL A
        ADC TI_T        ; x 5 (carry clear: A <= 17)
        LDY #0
        STY ZPTR+1
        ASL A           ; x 40
        ROL ZPTR+1
        ASL A
        ROL ZPTR+1
        ASL A
        ROL ZPTR+1
        CLC
        ADC #<TI_TXT
        STA ZPTR
        LDA ZPTR+1
        ADC #>TI_TXT
        STA ZPTR+1
        RTS
