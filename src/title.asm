; =====================================================================
;  TITLE.ASM -- the title screen (T-REL-1, D46; sunset T-REL-4, D70)
;
;  Shown at start-up and after the demo: a sunset over the sea after
;  Rube's reference picture.  "Acadia" in pale gold at the top left, a
;  sky in bands of colour with dark clouds drifting left, the high ones
;  faster than the low ones (players 0-2, TITLE_CLD.ASM), a black island with
;  the game's fort, the sun (player 3) setting to its right, a glitter
;  path on the water and REBUILD at the bottom right, a small PRESS
;  FIRE under it.  The graphics,
;  font and colour tables are generated by tools/mktitle.py
;  (TITLE_GFX.ASM).
;
;  A DLI on the last blank line runs TT_DLI, which sets COLBK, COLPF0
;  and COLPF1 every second scan line for the whole picture, and moves
;  and colours the cloud players; ST_VBI (STATUS.ASM) points VDSLST at
;  it while GSTATE is GS_TITLE, and each frame runs TT_CLD, which moves
;  the clouds that are due (D82).  TT_ANIM scatters new glitter on one row of the
;  water every TT_GRT frames (the rows in turn; the sun stays put,
;  Rube) and, after TT_PSEC seconds with nothing touched, shows PRESS
;  FIRE.
;
;  The clouds are players at quadruple width behind the playfield
;  (PRI_PF): P0 and P1 side by side for the long ones (lane 0), P2 for
;  the short ones (lane 1), each player reused down the sky.  TT_HA and
;  TT_HB hold each lane's horizontal position for every pair of lines;
;  TT_DLI writes them in the horizontal blank, so a cloud's position
;  can change anywhere.  Positions wrap at 256: a cloud that leaves on
;  the left comes back on the right.
;
;  The title tune plays.  Fire, START or any key, once everything has
;  been let go, goes on to the setup screen, with the tune still
;  playing.  Left alone for DM_IDLE seconds, it plays the demo
;  (DEMO.ASM), which comes back here.
;
;  Its display list, TDLIST, sits in DLIST's page like HDLIST.  The
;  water and the prompt are built in the map's screen memory (MAPSCR),
;  which the setup screen clears and the game redraws.
; =====================================================================

GS_TITLE = 5            ; GSTATE while the title screen is up
                        ; TITLEGFX, TTFONTA: MEM_A800.ASM / MEM_5200.ASM

; the picture's layout and glitter characters: as tools/mktitle.py
; makes them (TITLE_GFX.ASM's header lists the values)
TT_NL   =  96           ; colour table entries, 2 scan lines each
TT_WROWS = 3            ; mode 4 rows of water
TT_HORL =  144          ; the horizon: the picture's first water line
TT_SCOL =  35           ; the sun's character column (glitter path)
TG_SUN  =  14           ; gold glitter characters
TG_NSUN =  4
TG_BRT  =  18           ; bright glitter (inverse: PF3)
TG_NBRT =  2
TG_SKY  =  20           ; dim reflections of the sky (PF0)
TG_NSKY =  2

TT_SCR  =  MAPSCR       ; water: TT_WROWS mode 4 rows of 40, then the
TT_PRSO =  40*TT_WROWS  ; small PRESS FIRE, a mode 4 row (40), here
TT_HA   =  MAPSCR+512   ; per pair of lines: lane 0's position, past
                        ; the setup screen's text, which shows the
                        ; clouds too (D71)
TT_HB   =  TT_HA+TT_NL  ; and lane 1's (TT_DLI, SU_DLI)
TT_CX   =  TT_HB+TT_NL  ; per cloud: its position
TT_CT   =  TT_CX+TC_NUM ; and frames until it moves on
TT_QUAD =  3            ; SIZEP: quadruple width (the clouds)
TT_PMC  =  PM_P0+16+TC_PAIR ; the clouds' first P/M line (P0)
TT_PSEC =  10           ; idle seconds before PRESS FIRE shows
TT_GRT  =  12           ; frames between glitter changes (one row)
TT_SUNX =  HP_MAP+136   ; the sun's left edge (P/M): its centre is
                        ; colour clock 140, MKTITLE.PY's SUN_X
TT_HPM  =  [32+TT_HORL]/2 ; the horizon's double-line P/M line (the
                        ; picture starts at scan line 32)
TT_SUN0 =  TT_HPM-6     ; the sun's first P/M line: 12 of its 16 scan
                        ; lines above the horizon (it stays there)
TT_P3   =  PM_P0+[3*PM_LEN] ; player 3's memory: the sun
C_SUN   =  $1E          ; the sun (COLPM3, set by TT_DLI)
C_TBRT  =  $1E          ; the bright glitter (COLPF3)
C_TSHD  =  $00          ; the island and the logo's shadow (COLPF2)

; ---------------------------------------------------------------------
;  TITLE_ENTER -- show the title screen.  Trashes A, X, Y.
; ---------------------------------------------------------------------
TITLE_ENTER
        JSR MUS_TITLE
        LDA #0
        STA TI_ARM
        STA TI_SEC
        STA TT_PRS      ; PRESS FIRE not shown yet
        STA TT_GR       ; glitter: row 0 changes first
        LDA #TT_GRT-1
        STA TT_GFC
        JSR PM_INIT     ; P/M memory empty: no cursors, fish, weather
        JSR PM_HIDE     ; or pirates
        JSR TIC_SYNC    ; idle time counts from now
        LDA #0          ; the water and the prompt empty (512 bytes;
        TAX             ; the clouds' tables are past them)
TE_CLR  STA TT_SCR,X
        STA TT_SCR+256,X
        INX
        BNE TE_CLR
        LDX #TC_NPR-1   ; the clouds' shapes
TE_CLP  LDA TCP0,X
        STA TT_PMC,X
        LDA TCP1,X
        STA TT_PMC+PM_LEN,X
        LDA TCP2,X
        STA TT_PMC+PM_LEN+PM_LEN,X
        DEX
        BPL TE_CLP
        JSR TT_CINI     ; and their places
        LDA #TT_SUN0
        STA TT_SUN
        JSR TT_SUND     ; the sun in player 3
        JSR TT_GLIT     ; the first glitter
        LDA #>TTFONT    ; the scene's font, also the caption's letters
        STA CHBAS
        LDA TTP0        ; colours: the first line's, until TT_DLI sets
        STA COLOR0      ; each line's
        LDA TTP1
        STA COLOR1
        LDA #C_TSHD
        STA COLOR2
        LDA #C_TBRT
        STA COLOR3
        LDA TTBK
        STA COLOR4
        LDA #<TDLIST    ; same page as DLIST: one store switches
        STA SDLSTL
        LDA #GS_TITLE   ; last: from now on ST_VBI points the DLIs at
        STA GSTATE      ; TT_DLI, which must not run on the game's
        RTS             ; display list (it would starve the main loop)

; ---------------------------------------------------------------------
;  TITLE_FRAME -- each frame of the title screen: once everything is
;  let go, fire, START or any key goes on to the setup screen; after
;  DM_IDLE seconds with nothing touched, the demo.  Trashes A, X, Y.
; ---------------------------------------------------------------------
TITLE_FRAME
        LDA JOY0        ; anything touched: idle time from 0
        ORA JOY1
        ORA FIRE0
        ORA FIRE1
        ORA KEYDOWN
        ORA CONKEY
        BEQ TF_IDLE
        LDA #0
        STA TI_SEC
TF_IDLE JSR TIC_POLL    ; count the idle seconds
TF_TIC  JSR TIC_NEXT
        BCC TF_TDON
        BNE TF_TIC      ; not a new second
        INC TI_SEC
        BNE TF_TIC
TF_TDON JSR TT_ANIM     ; the glitter, the prompt
        LDA TI_SEC
        CMP #DM_IDLE
        BCC TF_KEYS
        JSR TT_LEAVE
        JMP DEMO_GO
TF_KEYS LDA FIRE0
        ORA FIRE1
        ORA KEYDOWN
        ORA CONKEY
        LDX TI_ARM
        BNE TF_ARMED
        CMP #0
        BNE TF_DONE     ; still held (OPTION at power-on, say)
        INC TI_ARM
TF_DONE RTS
TF_ARMED
        CMP #0
        BEQ TF_DONE
        JSR TT_LEAVE
        JMP SETUP_ENTER

; ---------------------------------------------------------------------
;  TT_ANIM -- each frame: PRESS FIRE once TI_SEC reaches TT_PSEC (it
;  stays up); every TT_GRT frames new glitter on the next water row.
;  Trashes A, X, Y.
; ---------------------------------------------------------------------
TT_ANIM
        LDA TT_PRS
        BNE TA_GL
        LDA TI_SEC
        CMP #TT_PSEC
        BCC TA_GL
        INC TT_PRS
        LDX #39
TA_PRS  LDA TTPRS,X
        STA TT_SCR+TT_PRSO,X
        DEX
        BPL TA_PRS
TA_GL   DEC TT_GFC
        BPL TA_DONE
        LDA #TT_GRT-1
        STA TT_GFC
        LDY TT_GR       ; the next row, round and round
        INY
        CPY #TT_WROWS
        BCC TA_ROW
        LDY #0
TA_ROW  STY TT_GR
        JMP TT_GROW
TA_DONE RTS

; ---------------------------------------------------------------------
;  TT_SUND -- draw the sun in player 3 (empty) from P/M line TT_SUN
;  down, cut off at the horizon (TT_HPM).  Trashes A, X, Y.
; ---------------------------------------------------------------------
TT_SUND
        LDX TT_SUN
        LDY #0
TV_ROW  CPX #TT_HPM
        BCS TV_DONE     ; under the horizon: hidden
        LDA TT_SUNS,Y
        STA TT_P3,X
        INX
        INY
        CPY #8
        BNE TV_ROW
TV_DONE RTS

TT_SUNS .BYTE $3C,$7E,$FF,$FF,$FF,$FF,$7E,$3C   ; 8 x 16 scan lines

; ---------------------------------------------------------------------
;  TT_LEAVE -- before the title screen hands over: P/M memory empty
;  (the sun, the clouds), the players' widths and priority as the game
;  has them (PM_INIT).  Trashes A, X.
; ---------------------------------------------------------------------
TT_LEAVE
        JMP PM_INIT

; ---------------------------------------------------------------------
;  TT_CINI -- the clouds as players 0-2, quadruple width, behind the
;  playfield, each cloud at its start and its lane's table filled.
;  TT_CSZ: only the players' width and priority.  Trashes A, X, Y
;  (TT_CSZ: A).
; ---------------------------------------------------------------------
TT_CINI
        JSR TT_CSZ
        LDX #TC_NUM-1
TE_CLD  LDA TC_X0,X
        STA TT_CX,X
        LDA TC_PER,X
        STA TT_CT,X
        JSR TK_FILL
        DEX
        BPL TE_CLD
        RTS
TT_CSZ  LDA #TT_QUAD
        STA SIZEP0
        STA SIZEP1
        STA SIZEP2
        LDA #PRI_PF
        STA GPRIOR
        RTS

; ---------------------------------------------------------------------
;  SU_CLDS -- the setup screen's clouds (D71): P/M memory empty, then
;  the title's clouds that lie within the logo rows (pairs of lines
;  before SU_SKY1), on the same P/M lines as on the title, since the
;  setup screen's logo sits where the title's does (D75).  From the
;  title (GSTATE still GS_TITLE) the clouds stay where they are, their
;  positions and lane tables kept; from the stats screen, whose game
;  drew over them, they start again (TT_CINI).  The VBI moves them
;  (TT_CLD); SU_GO empties P/M memory again.  Trashes A, X, Y.
; ---------------------------------------------------------------------
SU_NCP  =  SU_SKY1-TC_PAIR ; pairs of shapes copied

SU_CLDS
        JSR PM_INIT
        JSR PM_HIDE
        LDX #SU_NCP-1
SC_SHP  LDA TCP0,X
        STA TT_PMC,X
        LDA TCP1,X
        STA TT_PMC+PM_LEN,X
        LDA TCP2,X
        STA TT_PMC+PM_LEN+PM_LEN,X
        DEX
        BPL SC_SHP
        LDA GSTATE
        CMP #GS_TITLE
        BNE TT_CINI     ; after a game: from their starts
        JMP TT_CSZ      ; from the title: where they were (D75)

; ---------------------------------------------------------------------
;  TT_CLD -- each frame, from the VBI (ST_VBI, on the title and setup
;  screens, D82): every cloud whose time has come moves one colour
;  clock left (every TC_PER+1 frames: the high ones faster).  In the
;  VBI every step lands on its frame and before TT_DLI / SU_DLI read
;  the tables, so a cloud never moves late or shears for a frame.
;  Trashes A, X, Y.
; ---------------------------------------------------------------------
TT_CLD
        LDX #TC_NUM-1
TK_LOOP DEC TT_CT,X
        BPL TK_NEXT
        LDA TC_PER,X
        STA TT_CT,X
        DEC TT_CX,X     ; wraps at 0: back in from the right
        JSR TK_FILL
TK_NEXT DEX
        BPL TK_LOOP
        RTS

; ---------------------------------------------------------------------
;  TK_FILL -- cloud X's position into its lane's table (TT_HA or TT_HB)
;  for its pairs of lines and the two above (where TT_DLI moves the
;  player(s) there).  No variables, so the VBI (TT_CLD) and the main
;  loop (TT_CINI) can both run it.  Keeps X; trashes A, Y.
; ---------------------------------------------------------------------
TK_FILL
        LDA TC_L,X
        BNE TK_B
        LDY TC_E,X      ; from the last pair up
TK_A    DEY
        LDA TT_CX,X
        STA TT_HA,Y
        TYA
        CMP TC_A,X      ; down to the first
        BNE TK_A
        RTS
TK_B    LDY TC_E,X
TK_BL   DEY
        LDA TT_CX,X
        STA TT_HB,Y
        TYA
        CMP TC_A,X
        BNE TK_BL
        RTS

; ---------------------------------------------------------------------
;  TT_GLIT -- glitter on every water row (TT_GROW for each).
;  Trashes A, X, Y, TT_N.
; ---------------------------------------------------------------------
TT_GLIT
        LDY #0
TG_ALL  JSR TT_GROW
        INY
        CPY #TT_WROWS
        BNE TG_ALL
        RTS

; ---------------------------------------------------------------------
;  TT_GROW -- new glitter on water row Y: gold glints (TG_SUN...) in
;  two passes, a few close under the sun and a few further out
;  (TG_N within TG_W columns, the path widening down the rows), one
;  bright one (TG_BRT..., PF3) close under the sun, and one dim
;  reflection of the sky (TG_SKY...) anywhere.  Keeps Y; trashes A,
;  X, TT_N.
; ---------------------------------------------------------------------
TT_GROW
        LDA #40         ; the row empty
        STA TT_N
        LDX TG_R0,Y
        LDA #0
TG_CLR  STA TT_SCR,X
        INX
        DEC TT_N
        BNE TG_CLR
        TYA             ; the passes: 2 * row, 2 * row + 1
        PHA
        ASL A
        TAY
        INY
        JSR TG_PASS     ; further out
        DEY
        JSR TG_PASS     ; close under the sun
        LDA TG_W,Y      ; and a bright one there
        JSR RAND_N
        CLC
        ADC TG_X0,Y
        TAX
        LDA #TG_NBRT
        JSR RAND_N
        CLC
        ADC #TG_BRT+$80 ; inverse: its 11 pixels are PF3
        STA TT_SCR,X
        PLA             ; the row again
        TAY
        LDA #40         ; a reflection of the sky, anywhere
        JSR RAND_N
        CLC
        ADC TG_R0,Y
        TAX
        LDA #TG_NSKY
        JSR RAND_N
        CLC
        ADC #TG_SKY
        STA TT_SCR,X
        RTS

; TG_PASS -- pass Y's gold glints: TG_N of them within TG_W columns
; from TG_X0.  Keeps Y; trashes A, X, TT_N.
TG_PASS LDA TG_N,Y
        STA TT_N
TG_GOLD LDA TG_W,Y
        JSR RAND_N
        CLC
        ADC TG_X0,Y
        TAX
        LDA #TG_NSUN
        JSR RAND_N
        CLC
        ADC #TG_SUN
        STA TT_SCR,X
        DEC TT_N
        BNE TG_GOLD
        RTS

; per pass, two for each water row (TT_WROWS = 3), first close under
; the sun, then further out (as MKTITLE.PY's GL_PASS): gold glints,
; columns wide, first column
TG_N    .BYTE 3,1,2,2,2,2
TG_W    .BYTE 3,7,3,7,5,9
TG_X0   .BYTE TT_SCOL-1,TT_SCOL-3,40+TT_SCOL-1,40+TT_SCOL-3
        .BYTE 80+TT_SCOL-2,80+TT_SCOL-4
; per water row: its first byte
TG_R0   .BYTE 0,40,80

; ---------------------------------------------------------------------
;  TT_DLI -- the DLI on TDLIST's last blank line: the sun's position
;  and colour, then COLBK, COLPF0 and COLPF1 for every pair of scan
;  lines of the picture from TTBK, TTP0, TTP1 (TT_NL entries).  In the
;  horizontal blank after the first line of each pair, the clouds: on
;  even pairs their colour (COLPF0's shade) and lane 1's position
;  (TT_HB), on odd pairs lane 0's (TT_HA; P1 32 clocks right of P0).
;  It runs through the whole picture (192 lines); the title screen
;  does little else.  Keeps all registers.
; ---------------------------------------------------------------------
TT_DLI
        PHA
        TXA
        PHA
        TYA
        PHA
        LDA #TT_SUNX    ; the sun: player 3 (VBI_D hides it each frame)
        STA HPOSP3
        LDA #C_SUN
        STA COLPM3
        LDX #0
TD_LINE LDA TTBK,X      ; an even pair
        LDY TTP0,X
        STA WSYNC       ; at the end of a line: its colours for the
        STA COLBK       ; next two
        STY COLPF0
        LDA TTP1,X
        STA COLPF1
        STA WSYNC
        STY COLPM0      ; the clouds' shade
        STY COLPM1
        STY COLPM2
        LDA TT_HB,X     ; lane 1
        STA HPOSP2
        INX
        LDA TTBK,X      ; an odd pair
        LDY TTP0,X
        STA WSYNC
        STA COLBK
        STY COLPF0
        LDA TTP1,X
        STA COLPF1
        STA WSYNC
        LDA TT_HA,X     ; lane 0: P0, and P1 just right of it
        STA HPOSP0
        CLC
        ADC #32
        STA HPOSP1
        INX
        CPX #TT_NL
        BNE TD_LINE
        PLA
        TAY
        PLA
        TAX
        PLA
        RTI
